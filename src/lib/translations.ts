/**
 * Translates dynamic analysis text if in Hindi mode, otherwise returns original text.
 */
export function translateAnalysisText(text: string, lang: Language): string {
  if (lang !== 'hi' || !text) return text

  // Direct lookup
  if (analysisTextTranslations[text]) {
    return analysisTextTranslations[text]
  }

  // Handle common regex patterns (e.g., Top X%, Predicted X% watch-through, etc.)
  if (text.includes('Top ') && text.includes('% in your niche')) {
    return text.replace(/Top\s+(\d+%)\s+in your niche/i, 'आपकी श्रेणी में शीर्ष $1')
  }
  if (text.includes('Top ') && text.includes('%')) {
    return text.replace(/Top\s+(\d+%)/i, 'शीर्ष $1')
  }
  if (text.includes('Predicted') && text.includes('watch-through')) {
    return text.replace(/Predicted\s+(\d+%)\s+watch-through rate/i, 'पूर्वानुमानित $1 वॉच-थ्रू दर')
  }
  if (text.includes('Outperforms') && text.includes('similar content')) {
    return text.replace(/Outperforms\s+(\d+%)\s+of similar content in your niche/i, 'आपकी श्रेणी में $1 समान सामग्री से बेहतर प्रदर्शन')
  }
  if (text.startsWith('Fix: ')) {
    const key = text.replace('Fix: ', '')
    const translatedKey = analysisTextTranslations[key] || key
    return `सुधारें: ${translatedKey}`
  }

  return text
}
